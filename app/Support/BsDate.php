    /**
     * @return array{0: int, 1: int, 2: int} year, month (1–12), day
     */
    public static function fromAd(CarbonInterface $date): array
    {
        $days = (int) CarbonImmutable::parse(self::EPOCH)->diffInDays(CarbonImmutable::parse($date->toDateString()), false);
        if ($days < 0) {
            throw new InvalidArgumentException('Date is before BS 2000.');
        }
        foreach (self::DAYS as $year => $months) {
            $inYear = array_sum($months);
            if ($days >= $inYear) {
                $days -= $inYear;

                continue;
            }
            foreach ($months as $i => $len) {
                if ($days < $len) {
                    return [$year, $i + 1, $days + 1];
                }
                $days -= $len;
            }
        }

        throw new InvalidArgumentException('Date is after BS 2090.');
    }

    public static function toAd(int $year, int $month, int $day): CarbonImmutable
    {
        $months = self::DAYS[$year] ?? throw new InvalidArgumentException("BS year {$year} is out of range.");
        if ($month < 1 || $month > 12 || $day < 1 || $day > $months[$month - 1]) {
            throw new InvalidArgumentException('Not a valid BS date.');
        }
        $days = 0;
        foreach (self::DAYS as $y => $m) {
            if ($y >= $year) {
                break;
            }
            $days += array_sum($m);
        }
        $days += array_sum(array_slice($months, 0, $month - 1)) + $day - 1;

        return CarbonImmutable::parse(self::EPOCH)->addDays($days);
    }

    /**
     * "2083-04-01" style.
     */
    public static function format(CarbonInterface $date): string
    {
        [$y, $m, $d] = self::fromAd($date);

        return sprintf('%04d-%02d-%02d', $y, $m, $d);
    }

    /**
     * "1 Shrawan 2083" style.
     */
    public static function long(CarbonInterface $date): string
    {
        [$y, $m, $d] = self::fromAd($date);

        return $d.' '.self::MONTHS[$m - 1].' '.$y;
    }

    /**
     * Fiscal year (Shrawan–Asar) that contains the date, e.g. "2083/84", and its first AD day.
     *
     * @return array{label: string, starts_on: string}
     */
    public static function fiscalYear(CarbonInterface $date): array
    {
        [$y, $m] = self::fromAd($date);
        $start = $m >= 4 ? $y : $y - 1;

        return ['label' => $start.'/'.substr((string) ($start + 1), -2), 'starts_on' => self::toAd($start, 4, 1)->toDateString()];
    }
